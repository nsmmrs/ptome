/// Generates `lib/src/dictionaries.g.dart` from ICU 78.3's word-break
/// dictionaries (`icu4c/source/data/brkitr/dictionaries/`: `thaidict.txt`,
/// `laodict.txt`, `khmerdict.txt`, `burmesedict.txt`, at the tag
/// `release-78.3`; their terms are in `vendor/icu/LICENSE`): each word
/// list, one word a line, compressed by brotli (the `brotli` command) and
/// written as base64, decoded when a text first needs it.
///
/// ```sh
/// dart run tool/generate_dictionaries.dart ICU_DICTIONARY_DIR
/// ```
library;

import 'dart:convert';
import 'dart:io';

const Map<String, String> _files = {
  'Thai': 'thaidict.txt',
  'Laoo': 'laodict.txt',
  'Khmr': 'khmerdict.txt',
  'Mymr': 'burmesedict.txt',
};

void main(List<String> args) {
  if (args.length != 1) {
    stderr.writeln(
      'usage: dart run tool/generate_dictionaries.dart ICU_DICTIONARY_DIR',
    );
    exit(2);
  }
  final root = File(Platform.script.toFilePath()).parent.parent.path;
  final out = StringBuffer()
    ..writeln('// GENERATED CODE - DO NOT MODIFY BY HAND.')
    ..writeln('// Generated by `dart run tool/generate_dictionaries.dart` from')
    ..writeln("// ICU 78.3's word-break dictionaries (see vendor/icu/LICENSE).")
    ..writeln('// The word lists are long base64 strings: one line each.')
    ..writeln('// dart format off')
    ..writeln('// ignore_for_file: lines_longer_than_80_chars')
    ..writeln()
    ..writeln("/// The words ICU's dictionaries list for the scripts written")
    ..writeln('/// without spaces between words, by ISO 15924 code: one word a')
    ..writeln('/// line, compressed by brotli, in base64.')
    ..writeln('const Map<String, String> dictionaries = {');
  final work = Directory.systemTemp.createTempSync('dictionaries.');
  try {
    for (final MapEntry(key: script, value: file) in _files.entries) {
      final words = [
        for (final line in File('${args.first}/$file').readAsLinesSync())
          if (line.trim() case final word
              when word.isNotEmpty && !word.startsWith('#'))
            word,
      ];
      final plain = File('${work.path}/$script.txt')
        ..writeAsStringSync('${words.join('\n')}\n');
      final compressed = File('${work.path}/$script.br');
      final result = Process.runSync('brotli', [
        '-q',
        '11',
        '-f',
        '-o',
        compressed.path,
        plain.path,
      ]);
      if (result.exitCode != 0) throw StateError('brotli: ${result.stderr}');
      out.writeln(
        "  '$script': '${base64.encode(compressed.readAsBytesSync())}',",
      );
      stdout.writeln(
        '$script: ${words.length} words, '
        '${compressed.lengthSync()} bytes compressed',
      );
    }
  } finally {
    work.deleteSync(recursive: true);
  }
  out.writeln('};');
  File('$root/lib/src/dictionaries.g.dart').writeAsStringSync(out.toString());
}
