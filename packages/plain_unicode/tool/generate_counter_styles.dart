/// Generates `lib/src/counter_styles.g.dart`: the counter styles of
/// `vendor/w3c` (CSS Counter Styles Level 3's predefined ones, then the
/// W3C's Ready-made Counter Styles for the names CSS doesn't define), each
/// `@counter-style` rule's descriptors as written; and from
/// `vendor/cldr/48.2.0`, the numeric numbering systems' digits and each
/// locale's default numbering system.
///
/// ```sh
/// dart run tool/generate_counter_styles.dart
/// ```
library;

import 'dart:io';

void main() {
  final root = File(Platform.script.toFilePath()).parent.parent.path;
  final rules = <String, Map<String, String>>{};
  final css3 = <String>{};
  for (final file in [
    'css-counter-styles-3.css',
    'predefined-counter-styles.css',
  ]) {
    final css = File('$root/vendor/w3c/$file')
        .readAsStringSync()
        .replaceAll(RegExp(r'/\*.*?\*/', dotAll: true), '');
    for (final m in RegExp(
      r'@counter-style\s+([\w-]+)\s*\{([^}]*)\}',
    ).allMatches(css)) {
      final name = m[1]!.toLowerCase();
      if (rules.containsKey(name)) continue;
      if (file == 'css-counter-styles-3.css') css3.add(name);
      rules[name] = {
        for (final declaration in _declarations(m[2]!))
          declaration.$1: declaration.$2,
      };
    }
  }
  final out = StringBuffer()
    ..writeln('// GENERATED by tool/generate_counter_styles.dart from')
    ..writeln('// vendor/w3c (CSS Counter Styles Level 3, Ready-made Counter')
    ..writeln('// Styles) and vendor/cldr/48.2.0. Do not edit.')
    ..writeln()
    ..writeln("part of 'counter_styles.dart';")
    ..writeln()
    ..writeln('/// The counter styles the W3C defines, by name.')
    ..writeln('const Map<String, _Rule> _rules = {');
  final names = rules.keys.toList()..sort();
  for (final name in names) {
    final rule = rules[name]!;
    final system = rule['system'] ?? 'symbolic';
    final parts = system.split(RegExp(r'\s+'));
    final args = <String>[];
    switch (parts.first) {
      case 'extends':
        args
          ..add('_System.extension')
          ..add('extended: ${_quote(parts[1].toLowerCase())}');
      case 'fixed':
        args.add('_System.fixed');
        if (parts.length > 1) args.add('first: ${int.parse(parts[1])}');
      case final other:
        args.add('_System.$other');
    }
    // (The disclosure triangles' symbols are in CSS Counter Styles 3's
    // prose, 6.3: in horizontal left-to-right text.)
    final disclosure = {'disclosure-open': '▾', 'disclosure-closed': '▸'};
    if (disclosure[name] case final symbol? when rule['symbols'] == null) {
      rule['symbols'] = "'$symbol'";
    }
    if (rule['symbols'] case final symbols?) {
      args.add('symbols: [${_symbols(symbols).map(_quote).join(', ')}]');
    }
    if (rule['additive-symbols'] case final additive?) {
      final pairs = [
        for (final pair in additive.split(','))
          if (pair.trim().isNotEmpty) _additive(pair.trim()),
      ];
      final tuples = pairs.map((p) => '(${p.$1}, ${_quote(p.$2)})');
      args.add('additive: [${tuples.join(', ')}]');
    }
    if (rule['prefix'] case final prefix?) {
      args.add('prefix: ${_quote(_symbols(prefix).single)}');
    }
    if (rule['suffix'] case final suffix?) {
      args.add('suffix: ${_quote(_symbols(suffix).single)}');
    }
    if (rule['negative'] case final negative?) {
      final signs = _symbols(negative);
      args.add('negative: ${_quote(signs.first)}');
      if (signs.length > 1) args.add('negativeEnd: ${_quote(signs[1])}');
    }
    if (rule['range'] case final range? when range.trim() != 'auto') {
      final bounds = range.trim().split(RegExp(r'\s+'));
      String bound(String b) => b == 'infinite' ? 'null' : '${int.parse(b)}';
      args.add('range: (${bound(bounds[0])}, ${bound(bounds[1])})');
    }
    if (rule['pad'] case final pad?) {
      final m = RegExp(r'^(\d+)\s+(.*)$').firstMatch(pad.trim())!;
      args.add('pad: (${m[1]}, ${_quote(_symbols(m[2]!).single)})');
    }
    if (rule['fallback'] case final fallback?) {
      args.add('fallback: ${_quote(fallback.trim().toLowerCase())}');
    }
    out.writeln('  ${_quote(name)}: _Rule(${args.join(', ')}),');
  }
  out
    ..writeln('};')
    ..writeln()
    ..writeln(
      "/// CSS Counter Styles 3's predefined styles, which browsers know.",
    )
    ..writeln('const Set<String> _css3 = {')
    ..writeAll([
      for (final name in css3.toList()..sort()) '  ${_quote(name)},\n',
    ])
    ..writeln('};')
    ..writeln()
    ..writeln('/// The digits of the numeric numbering systems (CLDR), by id.')
    ..writeln('const Map<String, String> _numberingSystems = {');
  final cldr = '$root/vendor/cldr/48.2.0';
  for (final line in File('$cldr/numbering_systems.tsv').readAsLinesSync()) {
    if (line.isEmpty || line.startsWith('#')) continue;
    final [id, digits] = line.split('\t');
    out.writeln('  ${_quote(id)}: ${_quote(digits)},');
  }
  out
    ..writeln('};')
    ..writeln()
    ..writeln(
      "/// The locales' default numbering systems (CLDR), where not the",
    )
    ..writeln("/// root's (`latn`) or where a parent's isn't the locale's.")
    ..writeln('const Map<String, String> _defaultNumbering = {');
  for (final line in File(
    '$cldr/default_numbering_systems.tsv',
  ).readAsLinesSync()) {
    if (line.isEmpty || line.startsWith('#')) continue;
    final [locale, system] = line.split('\t');
    out.writeln('  ${_quote(locale)}: ${_quote(system)},');
  }
  out.writeln('};');
  File('$root/lib/src/counter_styles.g.dart').writeAsStringSync('$out');
  Process.runSync('dart', ['format', '$root/lib/src/counter_styles.g.dart']);
  stdout.writeln('${rules.length} counter styles');
}

/// The declarations of a rule's [body]: name and value.
Iterable<(String, String)> _declarations(String body) sync* {
  // (A `;` inside a string doesn't end a declaration.)
  var start = 0;
  String? quote;
  for (var i = 0; i < body.length; i++) {
    final c = body[i];
    if (quote != null) {
      if (c == r'\') {
        i++;
      } else if (c == quote) {
        quote = null;
      }
    } else if (c == '"' || c == "'") {
      quote = c;
    } else if (c == ';') {
      if (_declaration(body.substring(start, i)) case final d?) yield d;
      start = i + 1;
    }
  }
  if (_declaration(body.substring(start)) case final d?) yield d;
}

(String, String)? _declaration(String text) {
  final colon = text.indexOf(':');
  if (colon < 0) return null;
  return (
    text.substring(0, colon).trim().toLowerCase(),
    text.substring(colon + 1).trim(),
  );
}

/// The symbols of a descriptor's [value]: strings and identifiers (CSS
/// escapes resolved), separated by white space.
List<String> _symbols(String value) {
  final symbols = <String>[];
  var i = 0;
  while (i < value.length) {
    final c = value[i];
    if (c.trim().isEmpty) {
      i++;
      continue;
    }
    final out = StringBuffer();
    if (c == '"' || c == "'") {
      i++;
      while (i < value.length && value[i] != c) {
        i = _char(value, i, out);
      }
      i++;
    } else {
      while (i < value.length &&
          value[i].trim().isNotEmpty &&
          value[i] != ',') {
        i = _char(value, i, out);
      }
    }
    symbols.add('$out');
  }
  return symbols;
}

/// Reads one character (or CSS escape) of [value] at [i] into [out];
/// returns where the next starts.
int _char(String value, int i, StringBuffer out) {
  if (value[i] != r'\') {
    out.write(value[i]);
    return i + 1;
  }
  final hex = RegExp('[0-9a-fA-F]{1,6}').matchAsPrefix(value, i + 1);
  if (hex == null) {
    out.write(value[i + 1]);
    return i + 2;
  }
  out.writeCharCode(int.parse(hex[0]!, radix: 16));
  var next = hex.end;
  // (One white space after an escape belongs to it.)
  if (next < value.length && value[next] == ' ') next++;
  return next;
}

/// An additive tuple: its weight and symbol.
(int, String) _additive(String pair) {
  final m = RegExp(r'^(\d+)\s+(.*)$', dotAll: true).firstMatch(pair)!;
  return (int.parse(m[1]!), _symbols(m[2]!).join());
}

String _quote(String s) {
  final out = StringBuffer("'");
  for (final rune in s.runes) {
    switch (rune) {
      case 0x27:
        out.write(r"\'");
      case 0x5C:
        out.write(r'\\');
      case 0x24:
        out.write(r'\$');
      case < 0x20 || 0x7F || 0xA0 || 0x200B || 0x200C || 0x200D || 0x202F:
        out.write('\\u{${rune.toRadixString(16)}}');
      default:
        out.writeCharCode(rune);
    }
  }
  return "$out'";
}
