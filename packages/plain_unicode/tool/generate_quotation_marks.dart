/// Generates `lib/src/quotation_marks.g.dart` from the CLDR data in
/// `vendor/cldr/48.2.0`: each locale's quotation marks (its `delimiters`,
/// resolved), the parents of the locales that aren't their truncation
/// (`parentLocales`) and the likely scripts of the languages and of the
/// language-region pairs whose script differs (`likelySubtags`).
///
/// ```sh
/// dart run tool/generate_quotation_marks.dart
/// ```
///
/// With `--import MISC CORE` (the `cldr-misc-full` and `cldr-core` npm
/// packages, unpacked), the vendored files are written from them first.
library;

import 'dart:convert';
import 'dart:io';

const String _version = '48.2.0';

void main(List<String> args) {
  final root = File(Platform.script.toFilePath()).parent.parent.path;
  final vendor = '$root/vendor/cldr/$_version';
  if (args.length == 3 && args.first == '--import') {
    _import(args[1], args[2], vendor);
  }
  final marks = <String, List<String>>{
    for (final line in File('$vendor/delimiters.tsv').readAsLinesSync())
      if (line.isNotEmpty && !line.startsWith('#'))
        line.split('\t').first: line.split('\t').sublist(1),
  };
  final parents = <String, String>{
    for (final line in File('$vendor/parent_locales.tsv').readAsLinesSync())
      if (line.isNotEmpty && !line.startsWith('#'))
        line.split('\t')[0]: line.split('\t')[1],
  };
  final scripts = <String, String>{
    for (final line in File('$vendor/likely_scripts.tsv').readAsLinesSync())
      if (line.isNotEmpty && !line.startsWith('#'))
        line.split('\t')[0]: line.split('\t')[1],
  };
  final distinct = {for (final m in marks.values) m.join('\t')}.toList()
    ..sort();
  final out = StringBuffer()
    ..writeln('// GENERATED by tool/generate_quotation_marks.dart from CLDR')
    ..writeln('// $_version (vendor/cldr/$_version). Do not edit.')
    ..writeln()
    ..writeln("part of 'quotation_marks.dart';")
    ..writeln()
    ..writeln('/// The marks the locales use.')
    ..writeln('const List<QuotationMarks> _marks = [');
  for (final m in distinct) {
    final [start, end, alternateStart, alternateEnd] = m.split('\t');
    out.writeln(
      '  QuotationMarks._(${_quote(start)}, ${_quote(end)}, '
      '${_quote(alternateStart)}, ${_quote(alternateEnd)}),',
    );
  }
  out
    ..writeln('];')
    ..writeln()
    ..writeln("/// Each locale's marks (an index in [_marks]).")
    ..writeln('const Map<String, int> _locales = {');
  for (final locale in marks.keys.toList()..sort()) {
    out.writeln("  '$locale': ${distinct.indexOf(marks[locale]!.join('\t'))},");
  }
  out
    ..writeln('};')
    ..writeln()
    ..writeln("/// The parents of the locales that aren't their truncation")
    ..writeln('/// (`root`: none).')
    ..writeln('const Map<String, String> _parents = {');
  for (final MapEntry(:key, :value)
      in parents.entries.toList()..sort((a, b) => a.key.compareTo(b.key))) {
    out.writeln("  '$key': '$value',");
  }
  out
    ..writeln('};')
    ..writeln()
    ..writeln('/// The likely script of each language, and of the')
    ..writeln("/// language-region pairs whose script isn't the language's.")
    ..writeln('const Map<String, String> _scripts = {');
  for (final MapEntry(:key, :value)
      in scripts.entries.toList()..sort((a, b) => a.key.compareTo(b.key))) {
    out.writeln("  '$key': '$value',");
  }
  out.writeln('};');
  File('$root/lib/src/quotation_marks.g.dart').writeAsStringSync('$out');
  stdout.writeln(
    'wrote ${marks.length} locales, ${distinct.length} sets of marks',
  );
}

String _quote(String s) {
  final escaped = [
    for (final r in s.runes)
      if (r < 0x80 && r != 0x27 && r != 0x5c && r >= 0x20)
        String.fromCharCode(r)
      else
        '\\u{${r.toRadixString(16)}}',
  ].join();
  return "'$escaped'";
}

/// Writes the vendored files from the npm packages [misc] and [core].
void _import(String misc, String core, String vendor) {
  Directory(vendor).createSync(recursive: true);
  const header =
      '# From CLDR $_version (unicode-org/cldr-json, npm cldr-misc-full and '
      'cldr-core),\n# under the Unicode License v3 (LICENSE).\n';
  final delimiters = StringBuffer(
    '$header# locale, quotationStart, quotationEnd, alternateQuotationStart, '
    'alternateQuotationEnd\n',
  );
  final locales = [
    for (final dir in Directory('$misc/main').listSync())
      if (dir is Directory)
        dir.uri.pathSegments.where((s) => s.isNotEmpty).last,
  ]..sort();
  for (final locale in locales) {
    final file = File('$misc/main/$locale/delimiters.json');
    if (!file.existsSync()) continue;
    final json = jsonDecode(file.readAsStringSync()) as Map<String, Object?>;
    final main = json['main']! as Map<String, Object?>;
    final entry = main[locale]! as Map<String, Object?>;
    final d = entry['delimiters']! as Map<String, Object?>;
    delimiters.writeln(
      [
        if (locale == 'und') 'root' else locale,
        d['quotationStart'],
        d['quotationEnd'],
        d['alternateQuotationStart'],
        d['alternateQuotationEnd'],
      ].join('\t'),
    );
  }
  File('$vendor/delimiters.tsv').writeAsStringSync('$delimiters');

  Map<String, Object?> supplemental(String name) =>
      (jsonDecode(File('$core/supplemental/$name.json').readAsStringSync())
              as Map<String, Object?>)['supplemental']!
          as Map<String, Object?>;
  final parentLocales =
      (supplemental('parentLocales')['parentLocales']!
              as Map<String, Object?>)['parentLocale']!
          as Map<String, Object?>;
  final parentLines = [
    for (final MapEntry(:key, :value) in parentLocales.entries)
      '$key\t${value == 'und' ? 'root' : value}\n',
  ];
  File('$vendor/parent_locales.tsv').writeAsStringSync(
    '$header# locale, parent (root: none)\n${parentLines.join()}',
  );
  final likely =
      supplemental('likelySubtags')['likelySubtags']! as Map<String, Object?>;
  final scripts = StringBuffer(
    '$header# language or language-region, script\n',
  );
  final languages = {for (final locale in locales) locale.split('-').first};
  String scriptOf(Object? value) => (value! as String).split('-')[1];
  for (final MapEntry(:key, :value) in likely.entries) {
    // (Every language's, and each region's where its script isn't the
    // language's.)
    final keep = switch (key.split('-')) {
      [final language] => languages.contains(language),
      [final language, final region] =>
        region.length != 4 &&
            languages.contains(language) &&
            scriptOf(value) != scriptOf(likely[language]),
      _ => false,
    };
    if (keep) scripts.writeln('$key\t${scriptOf(value)}');
  }
  File('$vendor/likely_scripts.tsv').writeAsStringSync('$scripts');
  File('$core/LICENSE').copySync('$vendor/LICENSE');
}
