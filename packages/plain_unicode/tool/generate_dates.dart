/// Generates `lib/src/date_format.g.dart` from `vendor/cldr/48.2.0`:
/// each locale's calendar fields by path (`calendars.tsv`: month and day
/// names, day periods, eras, cyclic years, date, time and date-time
/// patterns, localized GMT formats), root's aliases between paths
/// (`calendar_aliases.tsv`), the eras' start dates (`eras.tsv`) and the
/// day periods' rules (`day_periods.tsv`), written by
/// `tool/import_cldr_calendars.py` from CLDR's XML.
///
/// ```sh
/// dart run tool/generate_dates.dart
/// ```
library;

import 'dart:io';

void main() {
  final root = File(Platform.script.toFilePath()).parent.parent.path;
  final cldr = '$root/vendor/cldr/48.2.0';
  Iterable<List<String>> rows(String name) sync* {
    for (final line in File('$cldr/$name').readAsLinesSync()) {
      if (line.isEmpty || line.startsWith('#')) continue;
      yield line.split('\t');
    }
  }

  final fields = <String, Map<String, String>>{};
  for (final [locale, path, value] in rows('calendars.tsv')) {
    (fields[locale] ??= {})[path] = value
        .replaceAll(r'\t', '\t')
        .replaceAll(r'\\', r'\');
  }
  final rules = <String, List<String>>{};
  for (final [locale, period, from, before] in rows('day_periods.tsv')) {
    int minutes(String time) {
      final [h, m] = time.split(':');
      return int.parse(h) * 60 + int.parse(m);
    }

    (rules[locale] ??= []).add(
      '(${_quote(period)}, ${minutes(from)}, '
      "${before.isEmpty ? 'null' : minutes(before)})",
    );
  }
  final out = StringBuffer()
    ..writeln('// GENERATED by tool/generate_dates.dart from CLDR 48.2.0')
    ..writeln('// (vendor/cldr/48.2.0). Do not edit.')
    ..writeln()
    ..writeln("part of 'date_format.dart';")
    ..writeln()
    ..writeln("/// Each locale's calendar fields it defines itself, by path.")
    ..writeln('const Map<String, Map<String, String>> _calendars = {');
  for (final locale in fields.keys.toList()..sort()) {
    out.writeln('  ${_quote(locale)}: {');
    for (final MapEntry(:key, :value) in fields[locale]!.entries) {
      out.writeln('    ${_quote(key)}: ${_quote(value)},');
    }
    out.writeln('  },');
  }
  out
    ..writeln('};')
    ..writeln()
    ..writeln(
      "/// Root's aliases: a path a field not found under is looked for",
    )
    ..writeln('/// under instead (the rest of the path kept).')
    ..writeln('const Map<String, String> _aliases = {');
  for (final [from, to] in rows('calendar_aliases.tsv')) {
    out.writeln('  ${_quote(from)}: ${_quote(to)},');
  }
  out
    ..writeln('};')
    ..writeln()
    ..writeln(
      "/// Each calendar's eras: the era, its first day's year, month and",
    )
    ..writeln("/// day, or (counted backwards) its last day's, and whether so.")
    ..writeln('const Map<String, List<(int, int, int, int, bool)>> _eras = {');
  final eras = <String, List<String>>{};
  for (final [calendar, era, start, end] in rows('eras.tsv')) {
    final backwards = start.isEmpty;
    final date = backwards ? end : start;
    // (A year below 1 written with a minus: -542-01-01.)
    final negative = date.startsWith('-');
    final [y, m, d] = (negative ? date.substring(1) : date).split('-');
    (eras[calendar] ??= []).add(
      '($era, ${negative ? '-' : ''}${int.parse(y)}, ${int.parse(m)}, '
      '${int.parse(d)}, $backwards)',
    );
  }
  for (final calendar in eras.keys) {
    out.writeln('  ${_quote(calendar)}: [${eras[calendar]!.join(', ')}],');
  }
  // (Week data: each region's first day and first week's fewest days;
  // the likely region of the languages CLDR has calendar data for.)
  final firstDays = <String, String>{};
  final minDays = <String, String>{};
  final likely = <String, String>{};
  final languages = {for (final l in fields.keys) l.split('-').first};
  for (final [kind, key, value] in rows('weeks.tsv')) {
    switch (kind) {
      case 'firstDay':
        firstDays[key] = value;
      case 'minDays':
        minDays[key] = value;
      case 'likely' when languages.contains(key.split('-').first):
        likely[key] = value;
    }
  }
  const days = ['mon', 'tue', 'wed', 'thu', 'fri', 'sat', 'sun'];
  out
    ..writeln('};')
    ..writeln()
    ..writeln(
      "/// Each region's first day of the week (1 Monday to 7 Sunday) and",
    )
    ..writeln(
      "/// the fewest days of a year its first week has; `001` the world's.",
    )
    ..writeln('const Map<String, (int, int)> _weeks = {');
  for (final region in {...firstDays.keys, ...minDays.keys}.toList()..sort()) {
    final first = days.indexOf(firstDays[region] ?? firstDays['001']!) + 1;
    out.writeln(
      '  ${_quote(region)}: ($first, ${minDays[region] ?? minDays['001']}),',
    );
  }
  out
    ..writeln('};')
    ..writeln()
    ..writeln("/// Each language's (or language and script's) likely region.")
    ..writeln('const Map<String, String> _likelyRegions = {');
  for (final key in likely.keys.toList()..sort()) {
    out.writeln('  ${_quote(key)}: ${_quote(likely[key]!)},');
  }
  out
    ..writeln('};')
    ..writeln()
    ..writeln(
      "/// The day periods' rules: a period, from (or at) and before, in",
    )
    ..writeln('/// minutes after midnight.')
    ..writeln('const Map<String, List<(String, int, int?)>> _dayPeriods = {');
  for (final locale in rules.keys.toList()..sort()) {
    out.writeln('  ${_quote(locale)}: [${rules[locale]!.join(', ')}],');
  }
  out.writeln('};');
  File('$root/lib/src/date_format.g.dart').writeAsStringSync('$out');
  Process.runSync('dart', ['format', '$root/lib/src/date_format.g.dart']);
  // (The Umm al-Qura calendar's month lengths: vendor/icu.)
  final umAlQura = StringBuffer()
    ..writeln('// GENERATED by tool/generate_dates.dart from ICU 78.3')
    ..writeln('// (vendor/icu/umalqura.tsv). Do not edit.')
    ..writeln()
    ..writeln(
      "/// The Umm al-Qura calendar's months, 1300 to 1600 AH: each year's",
    )
    ..writeln(
      '/// twelve as bits, Muharram the highest, 1 for 30 days, 0 for 29.',
    )
    ..writeln('const List<int> umAlQuraMonths = [');
  for (final line in File('$root/vendor/icu/umalqura.tsv').readAsLinesSync()) {
    if (line.isEmpty || line.startsWith('#')) continue;
    umAlQura.writeln('  ${line.split('\t')[1]},');
  }
  umAlQura.writeln('];');
  File('$root/lib/src/umalqura.g.dart').writeAsStringSync('$umAlQura');
  Process.runSync('dart', ['format', '$root/lib/src/umalqura.g.dart']);
  // (The algorithmic numbering systems' rules: vendor/cldr/48.2.0/rbnf.tsv.)
  final systems = <String, String>{};
  final ruleText = <String, StringBuffer>{};
  for (final row in rows('rbnf.tsv')) {
    switch (row) {
      case ['system', final id, final locale, final grouping, final ruleset]:
        systems[id] = "(${_quote('$locale/$grouping')}, ${_quote(ruleset)})";
      case ['rules', final locale, final grouping, final line]:
        (ruleText['$locale/$grouping'] ??= StringBuffer()).writeln(line);
    }
  }
  final rbnf = StringBuffer()
    ..writeln('// GENERATED by tool/generate_dates.dart from CLDR 48.2.0')
    ..writeln('// (vendor/cldr/48.2.0/rbnf.tsv). Do not edit.')
    ..writeln()
    ..writeln("/// The algorithmic numbering systems: each one's rules' source")
    ..writeln('/// (a file and grouping) and rule set.')
    ..writeln('const Map<String, (String, String)> rbnfSystems = {');
  for (final id in systems.keys.toList()..sort()) {
    rbnf.writeln('  ${_quote(id)}: ${systems[id]},');
  }
  rbnf
    ..writeln('};')
    ..writeln()
    ..writeln("/// Each source's rule text, a rule a line.")
    ..writeln('const Map<String, String> rbnfRules = {');
  for (final source in ruleText.keys.toList()..sort()) {
    final text = '${ruleText[source]}';
    rbnf.writeln('  ${_quote(source)}:');
    // (A line of rule text a string, joined.)
    final lines = text.split('\n')..removeLast();
    for (final (i, line) in lines.indexed) {
      rbnf.writeln(
        '    ${_quote('$line\n')}${i == lines.length - 1 ? ',' : ''}',
      );
    }
  }
  rbnf.writeln('};');
  File('$root/lib/src/rbnf.g.dart').writeAsStringSync('$rbnf');
  Process.runSync('dart', ['format', '$root/lib/src/rbnf.g.dart']);
  // (The astronomy's coefficients: vendor/erfa.)
  Iterable<List<String>> erfa(String name) sync* {
    for (final line in File('$root/vendor/erfa/$name').readAsLinesSync()) {
      if (line.isEmpty || line.startsWith('#')) continue;
      yield line.split('\t');
    }
  }

  final astronomy = StringBuffer()
    ..writeln('// GENERATED by tool/generate_dates.dart from ERFA')
    ..writeln('// (vendor/erfa, BSD-3-Clause). Do not edit.')
    ..writeln()
    ..writeln(
      "/// eraEpv00's Sun-to-Earth series in its ecliptic frame: for x, y",
    )
    ..writeln(
      '/// and z, the terms of T^0, T^1 and T^2, each its amplitude (au),',
    )
    ..writeln('/// phase (rad) and frequency (rad per Julian year).')
    ..writeln('const List<List<List<double>>> earthSeries = [');
  for (final component in const ['x', 'y', 'z']) {
    astronomy.writeln('  [');
    for (final power in const ['0', '1', '2']) {
      astronomy.writeln('    [');
      for (final [c, p, a, b, f] in erfa('earth.tsv')) {
        if (c == component && p == power) {
          astronomy.writeln('      $a, $b, $f,');
        }
      }
      astronomy.writeln('    ],');
    }
    astronomy.writeln('  ],');
  }
  astronomy
    ..writeln('];')
    ..writeln()
    ..writeln(
      "/// eraMoon98's (Meeus') longitude and distance terms: the multiples",
    )
    ..writeln(
      "/// of D, M, M' and F, the longitude's (deg) and distance's (m).",
    )
    ..writeln(
      'const List<(int, int, int, int, double, double)> moonLongitude = [',
    );
  for (final row in erfa('moon.tsv')) {
    if (row case [
      'lr',
      final d,
      final m,
      final mp,
      final f,
      final l,
      final r,
    ]) {
      astronomy.writeln('  ($d, $m, $mp, $f, $l, $r),');
    }
  }
  astronomy
    ..writeln('];')
    ..writeln()
    ..writeln(
      "/// eraMoon98's latitude terms: the multiples and the latitude's (deg).",
    )
    ..writeln('const List<(int, int, int, int, double)> moonLatitude = [');
  for (final row in erfa('moon.tsv')) {
    if (row case ['b', final d, final m, final mp, final f, final b]) {
      astronomy.writeln('  ($d, $m, $mp, $f, $b),');
    }
  }
  astronomy
    ..writeln('];')
    ..writeln()
    ..writeln(
      "/// eraNut00b's (IAU 2000B) luni-solar terms: the multiples of l, l',",
    )
    ..writeln(
      "/// F, D and Om, the longitude's sine, t sine and cosine coefficients",
    )
    ..writeln("/// (0.1 microarcsecond), and the obliquity's.")
    ..writeln('const List<List<double>> nutationTerms = [');
  for (final row in erfa('nutation.tsv')) {
    astronomy.writeln('  [${row.map(double.parse).join(', ')}],');
  }
  astronomy.writeln('];');
  File('$root/lib/src/astronomy.g.dart').writeAsStringSync('$astronomy');
  Process.runSync('dart', ['format', '$root/lib/src/astronomy.g.dart']);
  stdout.writeln('${fields.length} locales, ${rules.length} with day periods');
}

String _quote(String s) {
  // (Double quotes around an apostrophe, as the lints have it.)
  final quote = s.contains("'") && !s.contains('"') ? '"' : "'";
  final out = StringBuffer(quote);
  for (final rune in s.runes) {
    switch (rune) {
      case 0x27 when quote == "'":
        out.write(r"\'");
      case 0x5C:
        out.write(r'\\');
      case 0x24:
        out.write(r'\$');
      case < 0x20 ||
          0x7F ||
          0xA0 ||
          0x200B ||
          0x200C ||
          0x200D ||
          0x200E ||
          0x200F ||
          0x202F ||
          0x061C:
        out.write('\\u{${rune.toRadixString(16)}}');
      default:
        out.writeCharCode(rune);
    }
  }
  return '$out$quote';
}
