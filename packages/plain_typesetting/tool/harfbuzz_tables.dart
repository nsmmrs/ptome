/// Generates the shapers' data from a HarfBuzz 14.6.0 source checkout,
/// so the categories are exactly HarfBuzz's (its generators' rules over
/// Unicode 18 and Microsoft's additions):
///
/// - `lib/src/shaping/indic_data.g.dart`: each code point's Indic (and
///   Khmer, Myanmar) category and position, from
///   `hb_indic_get_categories` (`hb-ot-shaper-indic-table.cc`);
/// - `lib/src/shaping/use_data.g.dart`: each code point's Universal
///   Shaping Engine category, from `hb_use_get_category`
///   (`hb-ot-shaper-use-table.hh`);
/// - `lib/src/shaping/vowel_constraints.g.dart`: the vowel sequences each
///   script prohibits (`ms-use/IndicShapingInvalidCluster.txt`, as
///   `gen-vowel-constraints.py` reads it), before whose last character a
///   dotted circle goes.
///
/// The tables are dumped by small C++ programs compiled against the
/// checkout (a C++ compiler is needed):
///
///     dart run tool/harfbuzz_tables.dart HARFBUZZ_DIR
library;

import 'dart:io';

void main(List<String> args) {
  if (args.length != 1) {
    stderr.writeln('usage: dart run tool/harfbuzz_tables.dart HARFBUZZ_DIR');
    exit(2);
  }
  final hb = args.first;
  final work = Directory.systemTemp.createTempSync('harfbuzz_tables.');
  try {
    final indic = _dump(
      hb,
      work,
      'indic',
      r'''
#include "hb.hh"
#include "hb-ot-shaper-indic.hh"
#include <cstdio>
int main () {
  for (unsigned u = 0; u < 0x110000; u++)
    printf ("%u\n", (unsigned) hb_indic_get_categories (u));
}
''',
      ['hb-ot-shaper-indic-table.cc'],
    );
    final use = _dump(hb, work, 'use', r'''
#include "hb.hh"
#include "hb-ot-shaper-use-table.hh"
#include <cstdio>
int main () {
  for (unsigned u = 0; u < 0x110000; u++)
    printf ("%u\n", (unsigned) hb_use_get_category (u));
}
''', const []);
    _writeRanges(
      'lib/src/shaping/indic_data.g.dart',
      'indicCategoryRanges',
      "Each code point's Indic category (low byte) and position (high\n"
          "/// byte), as HarfBuzz 14.6.0's `hb_indic_get_categories` gives it",
      indic,
    );
    _writeRanges(
      'lib/src/shaping/use_data.g.dart',
      'useCategoryRanges',
      "Each code point's Universal Shaping Engine category, as\n"
          "/// HarfBuzz 14.6.0's `hb_use_get_category` gives it",
      use,
    );
    _writeVowelConstraints(hb);
  } finally {
    work.deleteSync(recursive: true);
  }
}

/// The value of every code point a C++ program built from [source] (and
/// [sources] of the checkout) prints.
List<int> _dump(
  String hb,
  Directory work,
  String name,
  String source,
  List<String> sources,
) {
  final file = File('${work.path}/$name.cc')..writeAsStringSync(source);
  final exe = '${work.path}/$name';
  final build = Process.runSync('c++', [
    '-std=c++17',
    '-O1',
    '-I$hb/src',
    '-o',
    exe,
    file.path,
    for (final s in sources) '$hb/src/$s',
  ]);
  if (build.exitCode != 0) throw StateError('c++ $name: ${build.stderr}');
  final run = Process.runSync(exe, const []);
  if (run.exitCode != 0) throw StateError('$name: ${run.stderr}');
  return [
    for (final line in (run.stdout as String).split('\n'))
      if (line.isNotEmpty) int.parse(line),
  ];
}

/// [values] (one per code point) as ranges of one value each, the most
/// common value left out: `start, end, value` triples.
void _writeRanges(String path, String name, String doc, List<int> values) {
  final counts = <int, int>{};
  for (final v in values) {
    counts[v] = (counts[v] ?? 0) + 1;
  }
  final common = counts.entries
      .reduce((a, b) => a.value >= b.value ? a : b)
      .key;
  final ranges = <int>[];
  var c = 0;
  while (c < values.length) {
    final v = values[c];
    var end = c;
    while (end + 1 < values.length && values[end + 1] == v) {
      end++;
    }
    if (v != common) ranges.addAll([c, end, v]);
    c = end + 1;
  }
  final out = StringBuffer()
    ..writeln('// GENERATED CODE - DO NOT MODIFY BY HAND.')
    ..writeln('// Generated by `dart run tool/harfbuzz_tables.dart` from')
    ..writeln("// HarfBuzz 14.6.0's tables (see vendor/harfbuzz/COPYING).")
    ..writeln('// dart format off')
    ..writeln('// ignore_for_file: lines_longer_than_80_chars')
    ..writeln()
    ..writeln('/// $doc: the value of the code points no range of')
    ..writeln('/// [$name] has.')
    ..writeln('const int ${name}Default = $common;')
    ..writeln()
    ..writeln('/// $doc, by ranges: each first and last code point, then the')
    ..writeln('/// value, in order.')
    ..writeln('const List<int> $name = [');
  for (var i = 0; i < ranges.length; i += 3) {
    out.writeln(
      '  0x${ranges[i].toRadixString(16)}, '
      '0x${ranges[i + 1].toRadixString(16)}, ${ranges[i + 2]},',
    );
  }
  out.writeln('];');
  File(path).writeAsStringSync(out.toString());
  stdout.writeln('$path: ${ranges.length ~/ 3} ranges');
}

/// The prohibited vowel sequences, by script (the script of their first
/// code point), each sequence that has a shorter one as its start left
/// out (as `gen-vowel-constraints.py`'s sets keep the shorter).
void _writeVowelConstraints(String hb) {
  const ucd = '../plain_unicode/vendor/ucd/18.0.0';
  // Long script names to ISO 15924 codes.
  final codes = <String, String>{};
  for (final line in File('$ucd/PropertyValueAliases.txt').readAsLinesSync()) {
    final fields = [for (final f in line.split('#').first.split(';')) f.trim()];
    if (fields.length >= 3 && fields[0] == 'sc') codes[fields[2]] = fields[1];
  }
  final scripts = <int, String>{};
  for (final line in File('$ucd/Scripts.txt').readAsLinesSync()) {
    final data = line.split('#').first.trim();
    if (data.isEmpty) continue;
    final [range, script] = [for (final f in data.split(';')) f.trim()];
    final bounds = range.split('..');
    for (
      var c = int.parse(bounds.first, radix: 16);
      c <= int.parse(bounds.last, radix: 16);
      c++
    ) {
      scripts[c] = codes[script]!;
    }
  }
  final byScript = <String, List<List<int>>>{};
  for (final line in File(
    '$hb/src/ms-use/IndicShapingInvalidCluster.txt',
  ).readAsLinesSync()) {
    final data = line.split('#').first.split(';').first.trim();
    if (data.isEmpty) continue;
    final sequence = [
      for (final c in data.split(RegExp(r'\s+'))) int.parse(c, radix: 16),
    ];
    (byScript[scripts[sequence.first]!] ??= []).add(sequence);
  }
  bool startsWith(List<int> a, List<int> b) {
    if (b.length > a.length) return false;
    for (var i = 0; i < b.length; i++) {
      if (a[i] != b[i]) return false;
    }
    return true;
  }

  final out = StringBuffer()
    ..writeln('// GENERATED CODE - DO NOT MODIFY BY HAND.')
    ..writeln('// Generated by `dart run tool/harfbuzz_tables.dart` from')
    ..writeln("// HarfBuzz 14.6.0's ms-use/IndicShapingInvalidCluster.txt")
    ..writeln('// (see vendor/harfbuzz/ms-use/COPYING).')
    ..writeln()
    ..writeln('/// The vowel sequences each script (by its ISO 15924 code)')
    ..writeln('/// prohibits: a dotted circle goes before the last character')
    ..writeln('/// of each.')
    ..writeln('const Map<String, List<List<int>>> vowelConstraints = {');
  for (final script in byScript.keys.toList()..sort()) {
    final kept = [
      for (final s in byScript[script]!)
        if (!byScript[script]!.any(
          (o) => o.length < s.length && startsWith(s, o),
        ))
          s,
    ];
    out.writeln("  '$script': [");
    for (final s in kept) {
      out.writeln(
        '    [${[for (final c in s) '0x${c.toRadixString(16)}'].join(', ')}],',
      );
    }
    out.writeln('  ],');
  }
  out.writeln('};');
  File('lib/src/shaping/vowel_constraints.g.dart')
      .writeAsStringSync(out.toString());
  stdout.writeln('vowel constraints: ${byScript.length} scripts');
}
