/// The tests on Node.js in a few programs rather than one a suite: every
/// suite that runs on Node (none marked `@TestOn('vm')`) imported into
/// one of [buckets] entry points under `build/node_tests`, each a group
/// per suite, so dart2js compiles a few programs, side by side, instead
/// of every suite in turn.
///
/// ```sh
/// dart run tool/node_tests.dart        # writes build/node_tests
/// dart test -p node build/node_tests
/// ```
library;

import 'dart:io';

/// How many programs the suites are dealt into.
const int buckets = 4;

void main() {
  final suites = [
    for (final entity in Directory('test').listSync(recursive: true))
      if (entity is File &&
          entity.path.endsWith('_test.dart') &&
          !entity.readAsStringSync().contains("@TestOn('vm')"))
        entity.path.replaceAll(r'\', '/'),
  ]..sort();
  final out = Directory('build/node_tests');
  if (out.existsSync()) out.deleteSync(recursive: true);
  out.createSync(recursive: true);
  // (Dealt in turn, so each program gets big and small suites alike.)
  for (var b = 0; b < buckets; b++) {
    final mine = [for (var i = b; i < suites.length; i += buckets) suites[i]];
    final source = StringBuffer()
      ..writeln('// Generated by tool/node_tests.dart: do not edit.')
      ..writeln("@TestOn('node')")
      ..writeln('library;')
      ..writeln()
      ..writeln("import 'package:test/test.dart';")
      ..writeln();
    for (final (i, suite) in mine.indexed) {
      source.writeln("import '../../$suite' as s$i;");
    }
    source
      ..writeln()
      ..writeln('void main() {');
    for (final (i, suite) in mine.indexed) {
      source.writeln("  group('$suite', s$i.main);");
    }
    source.writeln('}');
    File('${out.path}/bucket${b}_test.dart').writeAsStringSync('$source');
  }
  stdout.writeln('${suites.length} suites in $buckets programs: ${out.path}');
}
