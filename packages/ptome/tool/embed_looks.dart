/// Generates `lib/src/look/looks.g.dart` from `data/looks`: the built-in
/// looks (ADR-0023), embedded so no output reads files of its own to find
/// them. Run from the package folder after changing a look:
///
/// ```sh
/// dart run tool/embed_looks.dart          # write it
/// dart run tool/embed_looks.dart --check  # exit 1 if it is out of date
/// ```
library;

import 'dart:io';

void main(List<String> args) {
  final root = File(Platform.script.toFilePath()).parent.parent;
  final files =
      Directory('${root.path}/data/looks')
          .listSync()
          .whereType<File>()
          .where((f) => f.path.endsWith('-look.yml'))
          .toList()
        ..sort((a, b) => a.path.compareTo(b.path));
  final out = StringBuffer()
    ..writeln('// GENERATED CODE - DO NOT MODIFY BY HAND.')
    ..writeln('// Generated by `dart run tool/embed_looks.dart` from')
    ..writeln('// `data/looks` (${files.length} files).')
    ..writeln(
      '// ignore_for_file: lines_longer_than_80_chars, unnecessary_raw_strings, '
      'leading_newlines_in_multiline_strings',
    )
    ..writeln()
    ..writeln('/// The built-in looks (ADR-0023).')
    ..writeln('library;')
    ..writeln()
    ..writeln('/// The text of each built-in look, by name.')
    ..writeln('const Map<String, String> builtInLooks = {');
  for (final file in files) {
    final name = file.uri.pathSegments.last.replaceAll('-look.yml', '');
    final text = file.readAsStringSync();
    if (text.contains("'''")) {
      stderr.writeln("embed_looks: ${file.path} contains ''' ");
      exitCode = 1;
      return;
    }
    out.writeln("  '$name': r'''$text''',");
  }
  out.writeln('};');
  // (As dart format writes it, which the gate checks.)
  final scratch = Directory.systemTemp.createTempSync('embed_looks.');
  final generated = File('${scratch.path}/looks.g.dart')
    ..writeAsStringSync('$out');
  Process.runSync(Platform.resolvedExecutable, ['format', generated.path]);
  final formatted = generated.readAsStringSync();
  scratch.deleteSync(recursive: true);
  final target = File('${root.path}/lib/src/look/looks.g.dart');
  if (args.contains('--check')) {
    if (!target.existsSync() || target.readAsStringSync() != formatted) {
      stderr.writeln(
        'embed_looks: lib/src/look/looks.g.dart is out of date; run '
        'dart run tool/embed_looks.dart',
      );
      exitCode = 1;
    }
    return;
  }
  target.writeAsStringSync(formatted);
  stdout.writeln('embed_looks: ${files.length} looks');
}
