/// Writes the house look's values into `doc/style.md` (ADR-0023 decision
/// 5), between its `<!-- values: ... -->` and `<!-- end of values -->`
/// markers; `--check` exits 1 if they differ from the look's. Run from
/// the package folder after changing `data/looks/ptome-look.yml`:
///
/// ```sh
/// dart run tool/style_table.dart
/// ```
library;

import 'dart:io';

import 'package:ptome/src/look/describe.dart';
import 'package:ptome/src/look/loader.dart';

/// The start and end markers of the generated table.
const String start = '<!-- values: generated by tool/style_table.dart -->';
const String end = '<!-- end of values -->';

/// [doc] with the house look's values between its markers.
String withValues(String doc) {
  final from = doc.indexOf(start);
  final to = doc.indexOf(end);
  if (from < 0 || to < from) {
    throw StateError('doc/style.md has no $start ... $end markers');
  }
  final table = describeLook(LookLoader().load('ptome'));
  return '${doc.substring(0, from + start.length)}\n$table$end'
      '${doc.substring(to + end.length)}';
}

void main(List<String> args) {
  final file = File('doc/style.md');
  final doc = file.readAsStringSync();
  final updated = withValues(doc);
  if (args.contains('--check')) {
    if (updated != doc) {
      stderr.writeln(
        'style_table: doc/style.md differs from the house look; run '
        'dart run tool/style_table.dart',
      );
      exitCode = 1;
    }
    return;
  }
  file.writeAsStringSync(updated);
  stdout.writeln('style_table: doc/style.md written');
}
