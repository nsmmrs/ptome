/// A verse address in the sources: book (OSIS), chapter, verse.
typedef _Verse = (String, int, int);

void main(List<String> args) {
  if (args.length != 1) {
    stderr.writeln('usage: dart run tool/import_study_bible.dart SOURCES');
    exit(64);
  }
  final sources = args.single;
  final tosn = '$sources/tosn/Tyndale Open Study Notes';
  final xrefs = _crossReferences('$sources/xref/cross_references.txt');
  final notes = _items('$tosn/StudyNotes.xml');
  final features = [
    ..._items('$tosn/ThemeNotes.xml'),
    ..._items('$tosn/Profiles.xml'),
  ];
  final intros = _items('$tosn/BookIntros.xml');

  // (An excerpt: its books and chapters start where they like.)
  final out = StringBuffer()
    ..writeln(
      '= The Holy Bible (Genesis 1–3, Mark 1): Berean Standard Bible, with '
      'Tyndale Open Study Notes',
    )
    ..writeln(':units: bible, bsb-study')
    ..writeln(':excerpt:')
    ..writeln(':doctype: book')
    ..writeln(':sectids!:')
    ..writeln(':hyphens: en')
    ..writeln(':reproducible:')
    ..writeln()
    ..writeln(
      '// Generated by tool/import_study_bible.dart; the sources and their '
      'licenses: ../../NOTICE.md.',
    );
  for (final book in _books) {
    out
      ..writeln()
      ..writeln('== @${book.code}');
    final intro = intros
        .where((item) => item.refs.startsWith('${book.osis}.1.1-'))
        .firstOrNull;
    if (intro != null) out.write(_introduction(intro));
    _book(
      out,
      File('$sources/bsb/${book.usfm}').readAsStringSync(),
      book.osis,
      book.chapters,
      xrefs: xrefs,
      notes: notes,
      features: features,
    );
  }
  final target = File('test/units/corpus/bible/bsb-study/study.adoc')
    ..createSync(recursive: true)
    ..writeAsStringSync(
      '${out.toString().replaceAll(RegExp(r'\n{3,}'), '\n\n').trimRight()}\n',
    );
  stdout.writeln('wrote ${target.path}');
}

/// A Tyndale item: its name, the passage it is on (OSIS), its title and
/// its paragraphs (class, inner HTML).
typedef _Item = ({
  String name,
  String refs,
  String? title,
  List<(String, String)> paragraphs,
});

List<_Item> _items(String path) => [
  for (final m in RegExp(
    '<item name="([^"]*)"[^>]*>(.*?)</item>',
    dotAll: true,
  ).allMatches(File(path).readAsStringSync()))
    (
      name: m[1]!,
      refs: RegExp('<refs>([^<]*)</refs>').firstMatch(m[2]!)?[1] ?? '',
      title: RegExp('<title>([^<]*)</title>').firstMatch(m[2]!)?[1],
      paragraphs: [
        for (final p in RegExp(
          '<p class="([^"]*)">(.*?)</p>',
          dotAll: true,
        ).allMatches(m[2]!))
          (p[1]!, p[2]!),
      ],
    ),
];

/// The first verse of an item's passage (`Gen.1.1-2.3`: Gen 1:1).
_Verse? _start(String refs) {
  final m = RegExp(r'^(\w+)\.(\d+)\.(\d+)').firstMatch(refs);
  return m == null ? null : (m[1]!, int.parse(m[2]!), int.parse(m[3]!));
}

/// The cross-references of each verse: at least [_minVotes] votes, the
/// [_perVerse] most voted, in canonical order, written as references.
Map<_Verse, List<String>> _crossReferences(String path) {
  final byVerse = <_Verse, List<(String, int)>>{};
  for (final line in File(path).readAsLinesSync().skip(1)) {
    final [from, to, votes, ...] = line.split('\t');
    final count = int.tryParse(votes) ?? 0;
    final at = _start(from);
    if (at == null || count < _minVotes) continue;
    (byVerse[at] ??= []).add((to, count));
  }
  return {
    for (final MapEntry(:key, :value) in byVerse.entries)
      key: [
        for (final (to, _)
            in ([
                ...value,
              ]..sort((a, b) => b.$2.compareTo(a.$2))).take(_perVerse).toList()
              ..sort((a, b) => _order(a.$1).compareTo(_order(b.$1))))
          _reference(to),
      ],
  };
}

/// Where [osis] (`Isa.40.28`) falls in the canon, for ordering.
int _order(String osis) {
  final at = _start(osis);
  if (at == null) return 0;
  final (book, chapter, verse) = at;
  final index = _canon.indexWhere((b) => b.$1 == book);
  return index * 1000000 + chapter * 1000 + verse;
}

/// [osis] (`Isa.40.28`, `Isa.40.28-Isa.40.31`) as a reference
/// (`Isa 40:28`, `Isa 40:28–31`).
String _reference(String osis) {
  String one(String part) {
    final [book, chapter, verse] = part.split('.');
    final name = _canon.firstWhere(
      (b) => b.$1 == book,
      orElse: () => (book, book),
    );
    return '${name.$2} $chapter:$verse';
  }

  final [from, ...rest] = osis.split('-');
  if (rest.isEmpty) return one(from);
  final a = from.split('.');
  final b = rest.first.split('.');
  if (a[0] == b[0] && a[1] == b[1]) return '${one(from)}–${b[2]}';
  if (a[0] == b[0]) return '${one(from)}–${b[1]}:${b[2]}';
  return '${one(from)}–${one(rest.first)}';
}

/// The book introduction [item] as a sidebar before the book's text.
String _introduction(_Item item) {
  final out = StringBuffer()
    ..writeln()
    ..writeln('[.book-intro]')
    ..writeln('.Introduction to ${item.title ?? item.name}')
    ..writeln('****');
  for (final (kind, html) in item.paragraphs) {
    final text = _inline(html, inNote: false);
    out.writeln();
    if (kind == 'intro-h1' || kind == 'intro-sidebar-h1') {
      out
        ..writeln('[discrete]')
        ..writeln('==== $text');
    } else {
      out
        ..writeln('[.$kind]')
        ..writeln(text);
    }
  }
  out
    ..writeln()
    ..writeln('****');
  return out.toString();
}

/// A theme note or a profile as a sidebar.
String _feature(_Item item) {
  final out = StringBuffer()
    ..writeln()
    ..writeln('[.feature]')
    ..writeln('.${item.title ?? item.name}')
    ..writeln('****');
  for (final (kind, html) in item.paragraphs) {
    // (Its title is the sidebar's.)
    if (kind.endsWith('-title') && !kind.contains('refs')) continue;
    out
      ..writeln()
      ..writeln('[.$kind]')
      ..writeln(_inline(html, inNote: false));
  }
  out
    ..writeln()
    ..writeln('****');
  return out.toString();
}

/// Tyndale's [html] as AsciiDoc inline text: its spans in their classes
/// as roles (`sn-ref`, `sn-excerpt`, `hebrew`, `divine-name` as `nd`…),
/// italic as emphasis, links as their text; in a note's brackets
/// ([inNote]) with its closing brackets escaped.
String _inline(String html, {required bool inNote}) {
  var text = html
      .replaceAllMapped(RegExp('<a [^>]*>(.*?)</a>'), (m) => m[1]!)
      .replaceAll(RegExp(r'\s+'), ' ');
  // (In a note's brackets, the text's own closing brackets escaped.)
  if (inNote) text = text.replaceAll(']', r'\]');
  // (Innermost spans first.)
  final span = RegExp('<span class="([^"]*)">([^<]*)</span>');
  while (span.hasMatch(text)) {
    text = text.replaceAllMapped(span, (m) {
      final inner = m[2]!;
      if (inner.trim().isEmpty) return inner;
      return switch (m[1]!) {
        'ital' => '__${inner}__',
        'divine-name' => '[.nd]##$inner##',
        'divine-name-ital' => '__[.nd]##$inner##__',
        final role => '[.$role]##$inner##',
      };
    });
  }
  return text
      .replaceAll(RegExp('<[^>]*>'), '')
      .replaceAll('&amp;', '&')
      .replaceAll('&lt;', '<')
      .replaceAll('&gt;', '>')
      .replaceAll('&quot;', '"')
      .replaceAll('{', r'\{')
      .trim();
}

/// A study note [item] as a note of the stream `sn`; its list paragraphs
/// in the roles `sn-list-1`…
String _studyNote(_Item item) {
  final parts = [
    for (final (kind, html) in item.paragraphs)
      if (kind == 'sn-text')
        _inline(html, inNote: true)
      else
        '[.$kind]##${_inline(html, inNote: true)}##',
  ];
  return 'note:sn[${parts.join(' ')}]';
}

/// The text of [usfm]'s first [chapters] chapters of [book], in units.
void _book(
  StringBuffer out,
  String usfm,
  String book,
  int chapters, {
  required Map<_Verse, List<String>> xrefs,
  required List<_Item> notes,
  required List<_Item> features,
}) {
  // (USFM's word attributes and footnotes first.)
  final text = usfm
      .replaceAllMapped(
        RegExp(r'\\\+?w ([^|\\]*)\|[^\\]*\\\+?w\*'),
        (m) => m[1]!,
      )
      .replaceAllMapped(
        RegExp(r'\\f \+ \\fr [^\\]*\\ft ([^\\]*)\\f\*'),
        (m) => 'note:tn[${m[1]!.trim().replaceAll(']', r'\]')}]',
      );
  var chapter = 0;
  _Verse? verse;
  var poetry = false;
  final waiting = <String>[];

  // What follows the verse ending: its cross-references and the study
  // notes on passages it starts.
  String endOf(_Verse at) {
    final parts = <String>[];
    if (xrefs[at] case final refs?) parts.add('note:x[${refs.join('; ')}]');
    for (final note in notes) {
      if (_start(note.refs) == at) parts.add(_studyNote(note));
    }
    for (final feature in features) {
      if (_start(feature.refs) == at) waiting.add(_feature(feature));
    }
    return parts.join();
  }

  void closeVerse() {
    if (verse case final at?) out.write(endOf(at));
    verse = null;
  }

  void paragraphBreak() {
    closeVerse();
    out
      ..writeln()
      ..writeln();
    if (waiting.isNotEmpty) {
      out
        ..writeAll(waiting)
        ..writeln();
      waiting.clear();
    }
    poetry = false;
  }

  for (final raw in text.split('\n')) {
    final line = raw.trimRight();
    final m = RegExp(r'^\\(\w+)\s?(.*)$').firstMatch(line);
    if (m == null) continue;
    final (marker, rest) = (m[1]!, m[2]!.trim());
    switch (marker) {
      case 'c':
        chapter = int.parse(rest);
        if (chapter > chapters) {
          paragraphBreak();
          return;
        }
        paragraphBreak();
        out.writeln('=== @$chapter');
      case _ when chapter == 0 || chapter > chapters:
        continue;
      case 's1':
        paragraphBreak();
        out
          ..writeln('[discrete.pericope]')
          ..writeln('==== $rest');
      case 's2':
        paragraphBreak();
        out
          ..writeln('[discrete.subsection]')
          ..writeln('===== $rest');
      case 'r':
        paragraphBreak();
        out
          ..writeln('[.parallel]')
          ..writeln(rest);
      case 'b':
        paragraphBreak();
      case 'm' || 'p' || 'pmo' || 'pc' || 'li1':
        paragraphBreak();
        _verses(out, rest, book, chapter, (v) {
          closeVerse();
          verse = v;
        });
      case 'q1' || 'q2':
        if (!poetry) {
          paragraphBreak();
          out.writeln('[.poetry%hardbreaks]');
          poetry = true;
        } else if (rest.isNotEmpty) {
          out.writeln();
        }
        _verses(out, rest, book, chapter, (v) {
          closeVerse();
          verse = v;
        });
      case 'v':
        _verses(out, line.substring(1), book, chapter, (v) {
          closeVerse();
          verse = v;
        });
    }
  }
  paragraphBreak();
}

/// Writes [text] (`v 3 And God said…`, or text going on), each verse it
/// starts marked `@3` and reported to [started].
void _verses(
  StringBuffer out,
  String text,
  String book,
  int chapter,
  void Function(_Verse verse) started,
) {
  final parts = text.split(RegExp(r'\\v (?=\d)'));
  var first = true;
  for (final part in parts) {
    if (part.isEmpty) continue;
    final m = RegExp(r'^v? ?(\d+)\s(.*)$', dotAll: true).firstMatch(part);
    final isVerse = (!first || text.startsWith('v ')) && m != null;
    if (isVerse) {
      started((book, chapter, int.parse(m[1]!)));
      // (Each verse on a line of its own, as the corpus writes them.)
      if (out.isNotEmpty && !out.toString().endsWith('\n')) out.writeln();
      out.write('@${m[1]} ${m[2]!.trim()}');
    } else {
      if (out.isNotEmpty && !out.toString().endsWith('\n')) out.write(' ');
      out.write(part.trim());
    }
    first = false;
  }
}
