/// Writes the units corpus's study edition
/// (`test/units/corpus/bible/bsb-study/study.adoc`): the Berean Standard
/// Bible's text of Genesis 1–3 and Mark 1, with its translators' notes
/// (stream `tn`), OpenBible.info's cross-references (`x`, keyed by verse,
/// in the centre column) and Tyndale Open Study Notes (`sn`: the study
/// notes at their first verse, the theme notes and profiles as sidebars
/// after it, the book introductions before each book), from the sources
/// test/units/corpus/NOTICE.md names, unzipped into one folder:
///
///     dart run tool/import_study_bible.dart SOURCES
///
/// SOURCES holds `bsb/` (engbsb_usfm.zip), `xref/` (cross-references.zip)
/// and `tosn/` (tyndale_open-studynotes.zip).
library;

