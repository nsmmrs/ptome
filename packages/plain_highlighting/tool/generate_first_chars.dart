/// Generates `lib/src/first_chars_table.g.dart`: what each
/// language's matchers would work out from their expressions the first
/// time it is used (each rule's first characters and group count; see
/// `lib/src/precomputed.dart`). Run from the package root after the
/// grammars change (`tool/generate/generate.mjs`):
///
/// ```sh
/// dart run tool/generate_first_chars.dart
/// ```
library;

import 'dart:convert';
import 'dart:io';

import 'package:plain_highlighting/src/precomputed.dart';

void main() {
  final root = File(Platform.script.toFilePath()).parent.parent.path;
  final table = buildPrecomputedTable();
  final path = '$root/lib/src/first_chars_table.g.dart';
  File(path).writeAsStringSync(
    '// GENERATED CODE - DO NOT MODIFY BY HAND.\n'
    '// Generated by `dart run tool/generate_first_chars.dart`.\n'
    '// ignore_for_file: lines_longer_than_80_chars\n'
    '\n'
    "/// Each language's rules' first characters and group counts (see\n"
    '/// `precomputed.dart`), base64.\n'
    'library;\n'
    '\n'
    '/// The table, ${table.length} bytes.\n'
    "const String precomputedTable = '${base64Encode(table)}';\n",
  );
  Process.runSync(Platform.resolvedExecutable, ['format', path]);
  stdout.writeln('generate_first_chars: ${table.length} bytes');
}
