// Writes lib/src/vp8_tables.g.dart from the text of RFC 6386 (VP8 Data
// Format and Decoding Guide): the arrays it gives in C, read where they
// are declared, page breaks skipped, every number in order.
//
//   dart run tool/generate_vp8_tables.dart rfc6386.txt
import 'dart:io';

/// The numbers of the C array whose declaration begins with [declaration]
/// and has an initializer (`= { ... };`), in order.
List<int> table(List<String> lines, String declaration, int count) {
  // The text without page breaks (the footer, the form feed, the header)
  // or comments.
  final text = [
    for (final line in lines)
      if (!line.startsWith('Bankoski') &&
          !line.startsWith('RFC 6386') &&
          !line.contains('\f'))
        line.replaceAll(RegExp('//.*'), ''),
  ].join('\n').replaceAll(RegExp(r'/\*.*?\*/', dotAll: true), '');
  var from = 0;
  while (true) {
    final start = text.indexOf(declaration, from);
    if (start < 0) throw StateError('no $declaration with values');
    final equals = text.indexOf('=', start);
    final semicolon = text.indexOf(';', start);
    if (equals < 0 || semicolon < equals) {
      from = start + declaration.length;
      continue;
    }
    final open = text.indexOf('{', equals);
    final end = text.indexOf('};', open);
    final numbers = [
      for (final m in RegExp(r'-?\d+').allMatches(text.substring(open, end)))
        int.parse(m[0]!),
    ];
    if (numbers.length != count) {
      throw StateError('$declaration: ${numbers.length} numbers, not $count');
    }
    return numbers;
  }
}

void main(List<String> args) {
  final lines = File(args.single).readAsLinesSync();
  String list(String name, String doc, List<int> values) {
    final out = StringBuffer('/// $doc\nconst List<int> $name = [\n');
    for (var i = 0; i < values.length; i += 16) {
      out.writeln('  ${values.skip(i).take(16).join(', ')},');
    }
    return '$out];\n';
  }

  final out =
      StringBuffer('''
// Generated by tool/generate_vp8_tables.dart from RFC 6386; do not edit.
// The tables are the RFC's: code components of an IETF document, under
// the Simplified BSD License (the IETF Trust's Legal Provisions, 4.e).
// dart format off
// ignore_for_file: lines_longer_than_80_chars

''')
        ..writeln(
          list(
            'kfBmodeProbs',
            "The probabilities of a key frame's subblock modes, by the modes "
                'above\n/// and to the left (RFC 6386, 11.5): 10 × 10 × 9.',
            table(lines, 'const Prob kf_bmode_prob [num_intra_bmodes]', 900),
          ),
        )
        ..writeln(
          list(
            'coeffUpdateProbs',
            'The probabilities that a coefficient probability is updated (RFC '
                '6386,\n/// 13.4): 4 × 8 × 3 × 11.',
            table(
              lines,
              'const Prob coeff_update_probs [4] [8] [3] [num_dct_tokens-1]',
              1056,
            ),
          ),
        )
        ..writeln(
          list(
            'defaultCoeffProbs',
            'The default coefficient probabilities (RFC 6386, 13.5): '
                '4 × 8 × 3 × 11.',
            table(
              lines,
              'const Prob default_coeff_probs [4] [8] [3] '
              '[num_dct_tokens - 1]',
              1056,
            ),
          ),
        )
        ..writeln(
          list(
            'dcQuant',
            'The DC dequantization factors by quantizer index (RFC 6386, '
                '14.1).',
            table(lines, 'static const int dc_qlookup[QINDEX_RANGE]', 128),
          ),
        )
        ..writeln(
          list(
            'acQuant',
            'The AC dequantization factors by quantizer index (RFC 6386, '
                '14.1).',
            table(lines, 'static const int ac_qlookup[QINDEX_RANGE]', 128),
          ),
        );
  stdout.write('${out.toString().trimRight()}\n');
}
