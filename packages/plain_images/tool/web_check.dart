void main() {
  final out = BytesBuilder(copy: false);
  for (final image in _images) {
    final raster = ImageFile.read(base64.decode(image)).decode();
    out
      ..add(
        utf8.encode(
          '${raster.width} ${raster.height} '
          '${raster.colorModel.name} ${raster.bitDepth}',
        ),
      )
      ..add(raster.samples)
      ..add(raster.palette ?? const [])
      ..add(switch (raster.transparency) {
        AlphaChannel(:final samples) => samples,
        ColorKey(:final values) => values,
        null => const [],
      })
      ..add(raster.toRgba8());
  }
  // An Adler-32 style checksum: its sums stay small enough for
  // JavaScript's numbers.
  final bytes = out.takeBytes();
  var a = 1;
  var b = 0;
  for (final byte in bytes) {
    a = (a + byte) % 65521;
    b = (b + a) % 65521;
  }
  // The digest is the program's output.
  // ignore: avoid_print
  print('${bytes.length} $b-$a');
}
